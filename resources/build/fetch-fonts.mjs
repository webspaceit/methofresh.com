/**
 * Downloads the Google Fonts used by the storefront and rewrites the CSS to
 * point at locally hosted woff2 files.
 *
 *   node resources/build/fetch-fonts.mjs
 *
 * Outputs:
 *   public/assets/fonts/*.woff2    (committed)
 *   resources/css/fonts.css        (committed; @import-ed by app.css)
 *
 * Re-run only when the font families/weights below change.
 */
import { createHash } from 'node:crypto';
import { mkdir, writeFile, readdir, rm } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..', '..');
const fontsDir = path.join(root, 'public', 'assets', 'fonts');
const outCss = path.join(root, 'resources', 'css', 'fonts.css');

// Same families/weights the storefront previously requested from Google.
const GOOGLE_URL =
    'https://fonts.googleapis.com/css2' +
    '?family=Hind+Siliguri:wght@300;400;500;600;700' +
    '&family=Noto+Sans+Bengali:wght@400;500;600;700;800' +
    '&display=swap';

// A modern desktop UA makes Google serve woff2 + unicode-range subsets.
const UA =
    'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 ' +
    '(KHTML, like Gecko) Chrome/124.0.0.0 Safari/537.36';

const css = await (await fetch(GOOGLE_URL, { headers: { 'User-Agent': UA } })).text();

const faceRe = /@font-face\s*\{([^}]*)\}/g;
const faces = [];
let m;
while ((m = faceRe.exec(css)) !== null) faces.push(m[1]);

if (faces.length === 0) {
    console.error('No @font-face blocks returned by Google Fonts. Aborting.');
    process.exit(1);
}

const prop = (block, name) => {
    const r = new RegExp(name + '\\s*:\\s*([^;]+);', 'i').exec(block);
    return r ? r[1].trim() : '';
};

await mkdir(fontsDir, { recursive: true });
// Clean previously downloaded files so re-runs don't leave orphans around.
for (const f of await readdir(fontsDir).catch(() => [])) {
    if (f.endsWith('.woff2')) await rm(path.join(fontsDir, f));
}

const out = [
    '/* GENERATED by resources/build/fetch-fonts.mjs — do not edit by hand. */',
    '/* Self-hosted Google Fonts (Hind Siliguri + Noto Sans Bengali).',
    '   Replaces the external fonts.googleapis.com request. */',
    '',
];
let downloaded = 0;

for (const block of faces) {
    const family = prop(block, 'font-family').replace(/['"]/g, '');
    const style = prop(block, 'font-style') || 'normal';
    const weight = prop(block, 'font-weight') || '400';
    const range = prop(block, 'unicode-range');
    const urlMatch = /url\((https:\/\/fonts\.gstatic\.com\/[^)]+\.woff2)\)/.exec(block);
    if (!urlMatch) continue;

    const url = urlMatch[1];
    const name = createHash('sha1').update(url).digest('hex').slice(0, 16) + '.woff2';
    const buf = Buffer.from(await (await fetch(url, { headers: { 'User-Agent': UA } })).arrayBuffer());
    await writeFile(path.join(fontsDir, name), buf);
    downloaded++;

    out.push(
        '@font-face{',
        `font-family:'${family}';`,
        `font-style:${style};`,
        `font-weight:${weight};`,
        'font-display:swap;',
        `src:url('../fonts/${name}') format('woff2');`,
        range ? `unicode-range:${range};` : '',
        '}'
    );
}

await writeFile(outCss, out.filter(Boolean).join('\n') + '\n');
console.log(`Wrote ${downloaded} woff2 files to public/assets/fonts/ and ${path.relative(root, outCss)}`);
